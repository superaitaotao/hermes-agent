#!/usr/bin/env python3
"""Build, verify and install the immutable privileged admin bundle.

The broker runs as root outside the agent session, so its code must be pinned and
unreachable from any worker-writable path. A bundle is:

    <prefix>/opt/hermes-protected-writes/<artifact-sha256>/
        manifest.json      per-file sha256 + mode + size, artifact id over the payload
        tools/…            the exact source files the broker imports
    <prefix>/usr/local/libexec/hermes-protected-write-admin   the launcher

``artifact-sha256`` is the SHA-256 of the canonical manifest payload, so any byte
change to a bundled file changes the artifact id. ``verify`` fails closed on a
hash mismatch, a symlink, a hardlink, a foreign owner, or any writable ancestor.

D1 scope: build/verify/install of the recipe. D1 does NOT install anything on the
host and does not issue a grant; activation is a separate human-authorized step.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import stat
import sys
from pathlib import Path
from typing import Iterable, Mapping

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PREFIX = Path("/")
BUNDLE_ROOT_REL = Path("opt/hermes-protected-writes")
LAUNCHER_REL = Path("usr/local/libexec/hermes-protected-write-admin")
MANIFEST_NAME = "manifest.json"
MANIFEST_SCHEMA = "protected-write-bundle-v1"
CURRENT_POINTER = "current"

#: Exactly the modules the broker imports at runtime, plus its package markers.
BUNDLED_FILES: tuple[str, ...] = (
    "tools/__init__.py",
    "tools/protected_write_protocol.py",
    "tools/protected_write_context.py",
    "tools/protected_write_preparer.py",
    "tools/protected_write_authority.py",
    "tools/protected_write_broker.py",
    "tools/protected_write_client.py",
    "tools/file_operations_common.py",
    "tools/fuzzy_match.py",
    "tools/patch_parser.py",
)

#: Prefix of an importable shim so the bundled broker can run with a clean sys.path.
BOOTSTRAP_NAME = "bootstrap.py"
BOOTSTRAP_SOURCE = '''\
"""Bundle entry point: isolated import root, then the broker with a clean argv."""
import os
import runpy
import sys

BUNDLE_DIR = os.path.dirname(os.path.abspath(__file__))
# Bundle first, then the interpreter's own standard library: the worker's
# site-packages and user site can never satisfy an import here. The launcher also
# runs with -I -S, so no .pth file or PYTHONPATH can add an entry at all.
sys.path[:] = [BUNDLE_DIR] + [
    path for path in sys.path
    if path and not any(
        marker in path for marker in ("site-packages", "dist-packages", "user-site"))
]
os.chdir(BUNDLE_DIR)

if __name__ == "__main__":
    runpy.run_module("tools.protected_write_broker", run_name="__main__")
'''

LAUNCHER_SOURCE = """\
#!/bin/sh
# Generated by scripts/protected_write_bundle.py. Root-owned, hash-pinned, non-worker-writable.
set -eu
BUNDLE_ROOT="{bundle_root}"
POINTER="$BUNDLE_ROOT/current"
[ -f "$POINTER" ] || {{ echo "protected-write: no active bundle pointer" >&2; exit 4; }}
ARTIFACT="$(cat "$POINTER")"
BUNDLE="$BUNDLE_ROOT/$ARTIFACT"
[ -d "$BUNDLE" ] || {{ echo "protected-write: bundle $ARTIFACT is missing" >&2; exit 4; }}
exec /usr/bin/python3 -I -S "$BUNDLE/{bootstrap}" --bundle "$BUNDLE" "$@"
"""


class BundleError(RuntimeError):
    """The bundle cannot be built, verified or installed; callers must fail closed."""


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def canonical_manifest_bytes(payload: Mapping) -> bytes:
    return json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
        allow_nan=False).encode("utf-8")


def artifact_id_for(files: Mapping[str, Mapping[str, object]]) -> str:
    return hashlib.sha256(canonical_manifest_bytes(dict(files))).hexdigest()


def _check_path_component(path: Path, *, owner: int | None) -> None:
    st = os.lstat(path)
    if stat.S_ISLNK(st.st_mode):
        raise BundleError(f"{path} is a symlink")
    if st.st_mode & (stat.S_IWGRP | stat.S_IWOTH):
        raise BundleError(f"{path} is writable by group or other")
    if owner is not None and st.st_uid != owner:
        raise BundleError(f"{path} is owned by uid {st.st_uid}, expected {owner}")


def verify_ancestors(
    target: Path, *, owner: int | None = None, boundary: Path | None = None,
) -> None:
    """Every ancestor of ``target`` down to ``boundary`` must be non-writable.

    The boundary is inclusive and defaults to the filesystem root, so an installer
    verifies the whole path it deployed into. A caller that already owns a
    directory it created itself (the build's own test prefix) may stop there.
    """
    stop = Path("/") if boundary is None else Path(boundary)
    parts: list[Path] = []
    current = target
    while True:
        parts.append(current)
        if current == stop or current.parent == current:
            break
        current = current.parent
    for component in reversed(parts):
        if not component.exists():
            continue
        _check_path_component(component, owner=owner)


def verify_bundle(bundle_dir: Path, *, owner: int | None = None,
                  boundary: Path | None = None) -> dict:
    """Recompute every hash and ownership rule; raise :class:`BundleError` on any drift."""
    manifest_path = bundle_dir / MANIFEST_NAME
    if not manifest_path.is_file() or manifest_path.is_symlink():
        raise BundleError(f"{manifest_path} is missing or is a symlink")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema_version") != MANIFEST_SCHEMA:
        raise BundleError(f"unknown bundle manifest schema {manifest.get('schema_version')!r}")
    files = manifest.get("files")
    if not isinstance(files, dict) or not files:
        raise BundleError("manifest carries no files")
    if artifact_id_for(files) != manifest.get("artifact_sha256"):
        raise BundleError("manifest artifact id does not match its payload")
    if bundle_dir.name != manifest["artifact_sha256"]:
        raise BundleError(
            f"bundle directory {bundle_dir.name} is not the artifact id "
            f"{manifest['artifact_sha256']}")
    verify_ancestors(bundle_dir, owner=owner, boundary=boundary)
    for rel, entry in sorted(files.items()):
        path = bundle_dir / rel
        if not path.is_file() or path.is_symlink():
            raise BundleError(f"{rel} is missing or is a symlink")
        st = os.lstat(path)
        if st.st_nlink > 1:
            raise BundleError(f"{rel} has {st.st_nlink} hard links")
        if st.st_uid != (owner if owner is not None else st.st_uid):
            raise BundleError(f"{rel} is owned by uid {st.st_uid}, expected {owner}")
        if stat.S_IMODE(st.st_mode) != int(entry["mode"]):
            raise BundleError(
                f"{rel} mode {oct(stat.S_IMODE(st.st_mode))} != manifest "
                f"{oct(int(entry['mode']))}")
        if st.st_size != int(entry["size"]):
            raise BundleError(f"{rel} size changed")
        if _file_sha256(path) != entry["sha256"]:
            raise BundleError(f"{rel} content hash mismatch")
    return manifest


def build(source_root: Path, bundle_root: Path, *, files: Iterable[str] = BUNDLED_FILES) -> Path:
    """Materialise one artifact directory; returns its path."""
    entries: dict[str, dict[str, object]] = {}
    payloads: dict[str, bytes] = {}
    for rel in files:
        src = source_root / rel
        if not src.is_file():
            raise BundleError(f"required source {src} is missing")
        payloads[rel] = src.read_bytes()
    bootstrap = BOOTSTRAP_SOURCE.encode("utf-8")
    payloads[BOOTSTRAP_NAME] = bootstrap
    for rel, data in payloads.items():
        entries[rel] = {
            "sha256": hashlib.sha256(data).hexdigest(),
            "mode": 0o644,
            "size": len(data),
        }
    artifact = artifact_id_for(entries)
    target = bundle_root / artifact
    if target.exists():
        shutil.rmtree(target)
    # Every directory this build creates is non-writable by group and other, so the
    # artifact is verifiable in place regardless of the process umask (mkdir alone
    # inherits the umask, which may leave the directory group-writable).
    missing: list[Path] = []
    cursor = bundle_root
    while not cursor.exists():
        missing.append(cursor)
        cursor = cursor.parent
    for directory in reversed(missing):
        directory.mkdir()
        os.chmod(directory, 0o755)
    os.chmod(bundle_root, 0o755)
    for rel, data in payloads.items():
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        for directory in (target, *path.parents):
            if directory == bundle_root:
                break
            os.chmod(directory, 0o755)
        path.write_bytes(data)
        os.chmod(path, 0o644)
    os.chmod(target, 0o755)
    manifest = {
        "schema_version": MANIFEST_SCHEMA,
        "artifact_sha256": artifact,
        "files": entries,
    }
    (target / MANIFEST_NAME).write_bytes(canonical_manifest_bytes(manifest) + b"\n")
    os.chmod(target / MANIFEST_NAME, 0o644)
    return target


def install_launcher(bundle_root: Path, launcher_path: Path) -> None:
    """Write the launcher and (re)point ``current`` at the newest verified bundle."""
    launcher_path.parent.mkdir(parents=True, exist_ok=True)
    launcher_path.write_text(
        LAUNCHER_SOURCE.format(bundle_root=str(bundle_root),
                               bootstrap=BOOTSTRAP_NAME),
        encoding="utf-8")
    os.chmod(launcher_path, 0o755)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="protected_write_bundle",
        description="Build/verify/install the immutable protected-write admin bundle.")
    parser.add_argument("--prefix", default=str(DEFAULT_PREFIX),
                        help="install prefix (tests use a temp directory)")
    sub = parser.add_subparsers(dest="command", required=True)

    build_parser = sub.add_parser("build", help="materialise a new artifact directory")
    build_parser.add_argument("--source", default=str(REPO_ROOT))

    verify_parser = sub.add_parser("verify", help="verify one artifact (or the active one)")
    verify_parser.add_argument("artifact", nargs="?")
    verify_parser.add_argument("--owner", type=int, default=None,
                               help="require this owning uid for every file and ancestor")
    verify_parser.add_argument("--boundary", default=None,
                               help="stop the ancestor check at this directory "
                                    "(default: the filesystem root)")

    sub.add_parser("artifact-id", help="print the artifact id of the active bundle")
    args = parser.parse_args(argv)

    bundle_root = Path(args.prefix) / BUNDLE_ROOT_REL
    launcher = Path(args.prefix) / LAUNCHER_REL

    if args.command == "build":
        target = build(Path(args.source), bundle_root)
        install_launcher(bundle_root, launcher)
        (bundle_root / CURRENT_POINTER).write_text(target.name, encoding="utf-8")
        # A build can only attest the tree it just created; the installer's default
        # verify walks every ancestor up to the filesystem root.
        manifest = verify_bundle(target, boundary=bundle_root)
        print(json.dumps({"artifact_sha256": manifest["artifact_sha256"],
                          "bundle": str(target)}, sort_keys=True))
        return 0

    if args.command == "artifact-id":
        pointer = bundle_root / CURRENT_POINTER
        if not pointer.is_file():
            print("no active bundle pointer", file=sys.stderr)
            return 4
        print(pointer.read_text(encoding="utf-8").strip())
        return 0

    artifact = args.artifact
    if artifact is None:
        pointer = bundle_root / CURRENT_POINTER
        if not pointer.is_file():
            print("no active bundle pointer", file=sys.stderr)
            return 4
        artifact = pointer.read_text(encoding="utf-8").strip()
    try:
        manifest = verify_bundle(bundle_root / artifact, owner=args.owner,
                                 boundary=None if args.boundary is None else Path(args.boundary))
    except BundleError as exc:
        print(f"bundle verification failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps({"artifact_sha256": manifest["artifact_sha256"], "verified": True},
                     sort_keys=True))
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main()
    raise SystemExit(main())
